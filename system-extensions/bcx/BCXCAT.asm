* BCX KNOWN OPTIONAL PACKAGE CATALOG FOR INSTALLED OBJECT PDS.
* EXTLIB DD IS THE MANIFEST-MANAGED OPTIONAL OBJECT PDS (FB80).
* KEEP BCPLDEMO/BCPLTIME PATHS; Q.5 ADDS G!200 BCPLQSAM.
         MACRO
         BCXCAT &PKG
         GBLA  &BXGOOD
         GBLC  &BXCLIB,&BXCBEG,&BXCFIN
         AIF   ('&PKG' EQ 'BCPLDEMO').DEMO
         AIF   ('&PKG' EQ 'BCPLTIME').TIME
         AIF   ('&PKG' EQ 'BCPLQSAM').QSAM
         MNOTE 8,'UNKNOWN INSTALLED PACKAGE: &PKG'
         AGO   .EXIT
.DEMO    ANOP
&BXCLIB  SETC  'EXTLIB(BCPLDEMO)'
&BXCBEG  SETC  'DMOBEG'
&BXCFIN  SETC  'DMOEND'
&BXGOOD  SETA  1
         AGO   .EXIT
.TIME    ANOP
&BXCLIB  SETC  'EXTLIB(BCPLTIME)'
&BXCBEG  SETC  'TIMBEG'
&BXCFIN  SETC  'TIMEND'
&BXGOOD  SETA  1
         AGO   .EXIT
.QSAM    ANOP
&BXCLIB  SETC  'EXTLIB(BCPLQSAM)'
&BXCBEG  SETC  'QSMBEG'
&BXCFIN  SETC  'QSMEND'
&BXGOOD  SETA  1
.EXIT    ANOP
         MEND
