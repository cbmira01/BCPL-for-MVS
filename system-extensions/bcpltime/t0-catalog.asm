* T.0 SOURCE-MODE CATALOG; NEVER INSTALL AS EXT_MAC(BCXCAT).
* USE WITH ACCEPTED BCXPRE AND BCXPOST IN TEMPORARY MVS JOB.
* TIMEOBJ DD POINTS TO TEMPORARY BCPLTIME FB80 OBJECT DECK.
         MACRO
         BCXCAT &PKG
         GBLA  &BXGOOD
         GBLC  &BXCLIB,&BXCBEG,&BXCFIN
         AIF   ('&PKG' EQ 'BCPLTIME').TIME
         MNOTE 8,'UNKNOWN T0 SOURCE PACKAGE: &PKG'
         AGO   .EXIT
.TIME    ANOP
&BXCLIB  SETC  'TIMEOBJ'
&BXCBEG  SETC  'TIMBEG'
&BXCFIN  SETC  'TIMEND'
&BXGOOD  SETA  1
.EXIT    ANOP
         MEND
