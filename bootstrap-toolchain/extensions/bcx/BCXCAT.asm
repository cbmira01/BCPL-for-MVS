* R.5 MVS PACKAGE CATALOG FOR INSTALLED OBJECT PDS.
* EXTLIB DD IS AN APPROVED OPTIONAL OBJECT LIBRARY (FB80/PDS).
* ADD NEW PACKAGES BY REVIEWING CL8 IDS AND BCEX EXPORT SYMBOLS.
         MACRO
         BCXCAT &PKG
         GBLA  &BXGOOD
         GBLC  &BXCLIB,&BXCBEG,&BXCFIN
         AIF   ('&PKG' EQ 'BCPLDEMO').DEMO
         MNOTE 8,'UNKNOWN INSTALLED PACKAGE: &PKG'
         AGO   .EXIT
.DEMO    ANOP
&BXCLIB  SETC  'EXTLIB(BCPLDEMO)'
&BXCBEG  SETC  'DMOBEG'
&BXCFIN  SETC  'DMOEND'
&BXGOOD  SETA  1
.EXIT    ANOP
         MEND
