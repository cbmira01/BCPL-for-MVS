* T.1 KNOWN OPTIONAL PACKAGE CATALOG FOR INSTALLED OBJECT PDS.
* EXTLIB DD IS THE MANIFEST-MANAGED OPTIONAL OBJECT PDS (FB80).
* KEEP THE R.5 BCPLDEMO PATH UNCHANGED; ADD G!201 BCPLTIME.
         MACRO
         BCXCAT &PKG
         GBLA  &BXGOOD
         GBLC  &BXCLIB,&BXCBEG,&BXCFIN
         AIF   ('&PKG' EQ 'BCPLDEMO').DEMO
         AIF   ('&PKG' EQ 'BCPLTIME').TIME
         MNOTE 8,'UNKNOWN INSTALLED PACKAGE: &PKG'
         AGO   .EXIT
.DEMO    ANOP
&BXCLIB  SETC  'EXTLIB(BCPLDEMO)'
&BXCBEG  SETC  'DMOBEG'
&BXCFIN  SETC  'DMOEND'
&BXGOOD  SETA  1
         AGO   .EXIT
.TIME    ANOP
&BXCLIB  SETC  'EXTLIB(BCPLTIME)'
&BXCBEG  SETC  'TIMBEG'
&BXCFIN  SETC  'TIMEND'
&BXGOOD  SETA  1
.EXIT    ANOP
         MEND
