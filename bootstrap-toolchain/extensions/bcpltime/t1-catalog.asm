* T.1 SOURCE-ONLY BCX CATALOG: TWO TEMPORARY OBJECT DECKS.
* NOT THE INSTALLED EXT_MAC(BCXCAT). NO PERMANENT PDS WRITES.
         MACRO
         BCXCAT &PKG
         GBLA  &BXGOOD
         GBLC  &BXCLIB,&BXCBEG,&BXCFIN
         AIF   ('&PKG' EQ 'BCPLDEMO').DEMO
         AIF   ('&PKG' EQ 'BCPLTIME').TIME
         MNOTE 8,'UNKNOWN T1 SOURCE PACKAGE: &PKG'
         AGO   .EXIT
.DEMO    ANOP
&BXCLIB  SETC  'DEMOOBJ'
&BXCBEG  SETC  'DMOBEG'
&BXCFIN  SETC  'DMOEND'
&BXGOOD  SETA  1
         AGO   .EXIT
.TIME    ANOP
&BXCLIB  SETC  'TIMEOBJ'
&BXCBEG  SETC  'TIMBEG'
&BXCFIN  SETC  'TIMEND'
&BXGOOD  SETA  1
.EXIT    ANOP
         MEND
