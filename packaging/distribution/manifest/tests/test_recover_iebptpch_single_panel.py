"""Offline recovery tests: no real JES, no WSL checkout files."""
from __future__ import annotations

import hashlib
import importlib.util
import json
from pathlib import Path
import tempfile
import unittest
from types import SimpleNamespace

ROOT = Path(__file__).resolve().parents[4]
SOURCE = ROOT / 'tools/distribution/recover-iebptpch-single-panel.py'
SPEC = importlib.util.spec_from_file_location('ta0_recover_panel', SOURCE)
assert SPEC is not None and SPEC.loader is not None
mod = importlib.util.module_from_spec(SPEC)
SPEC.loader.exec_module(mod)

KEY = 'EXT_OBJ'
DSN = 'HERC02.BCPL.EXT.OBJ'
MEMBERS = ['BCPLDEMO', 'BCPLTIME', 'BCPLQSAM']
JOBS = [9046, 9047, 9048]


def digest(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def write_json(path: Path, value) -> None:
    path.write_text(json.dumps(value) + '\n', encoding='utf-8')


class FakeDecoder:
    def __init__(self):
        self.process_calls = []

    def load_evidence(self, directory: Path):
        name = directory.name.split('-', 1)[1].removesuffix('-pilot')
        receipt = json.loads((directory / 'receipt.json').read_text())
        report = (directory / 'job-report.txt').read_text()
        pins = {'job-report.txt': digest(report.encode()),
                'printer-window.raw': digest((directory / 'printer-window.raw').read_bytes())}
        return receipt, report, pins

    def decode_multi(self, report: str, *, job: int, jobname: str, members: list[str]):
        name = members[0]
        # No original bytes are generated by this fake; only fixed fixture data.
        binary = bytes([len(name)]) * 80
        return {name: (binary, {
            'record_count': 1, 'byte_count': 80,
            'sha256_of_decoded_print': digest(binary), 'member': name,
            'job': job,
        })}

    def process(self, evidence: Path, output: Path, *, expected_counts: list[str]):
        self.process_calls.append(evidence.name)
        receipt, report, pins = self.load_evidence(evidence)
        member = receipt['requested_members'][0]
        binary, meta = self.decode_multi(report, job=receipt['job'],
                                         jobname=receipt['jobname'], members=[member])[member]
        output.mkdir(mode=0o700)
        (output / f'{member}.fb80').write_bytes(binary)
        write_json(output / f'{member}.fb80.json', meta)
        overall = {
            'source_job': receipt['job'], 'source_dataset': DSN,
            'source_receipt_sha256': digest((evidence / 'receipt.json').read_bytes()),
            'source_report_sha256': pins['job-report.txt'],
            'source_printer_window_sha256': pins['printer-window.raw'],
            'members': [meta],
        }
        write_json(output / 'decode-receipt.json', overall)
        return overall


class RecoveryTests(unittest.TestCase):
    def setUp(self):
        self.temp = tempfile.TemporaryDirectory()
        self.addCleanup(self.temp.cleanup)
        self.root = Path(self.temp.name) / 'ext-panel'
        self.root.mkdir(mode=0o700)
        self.decoder = FakeDecoder()
        def safe_json(path, data):
            if path.exists():
                raise RuntimeError('would overwrite file')
            write_json(path, data)
        self.panel = SimpleNamespace(ALLOWED={'EXT_OBJ': 'E'}, safe_json=safe_json)
        self.pilots=[]
        for i, (name, job) in enumerate(zip(MEMBERS, JOBS), 1):
            pilot = self.root / f'{i:02d}-{name}-pilot'
            pilot.mkdir()
            self.pilots.append(pilot)
            write_json(pilot / 'receipt.json', {
                'dataset_key': KEY, 'source_dataset': DSN,
                'requested_members': [name], 'jobname': f'TA0E{i:03d}',
                'job': job, 'step': 'TA0HEX',
            })
            (pilot / 'job-report.txt').write_text('CLEAN JES JOB REPORT\n')
            (pilot / 'printer-window.raw').write_bytes(b'READ ONLY ORIGINAL\n')
            if i < 3:
                self.decoder.process(pilot, self.root / f'{i:02d}-{name}-decoded',
                                     expected_counts=[])
        self.decoder.process_calls=[]
        write_json(self.root / 'failure.json', {
            'stage': 'decode', 'ordinal': 3, 'failed_member': MEMBERS[2],
            'pilot_job': JOBS[2], 'exception_type': 'MultiError',
        })

    def recover(self):
        return mod.recover(self.panel, self.decoder, directory=self.root,
                           key=KEY, members=MEMBERS, source_dataset=DSN)

    def test_recover_without_new_mvs_job(self):
        receipt = self.recover()
        self.assertEqual(receipt['completed'], 3)
        self.assertEqual([x['job'] for x in receipt['members']], JOBS)
        self.assertEqual(self.decoder.process_calls, ['03-BCPLQSAM-pilot'])
        self.assertTrue((self.root / '03-BCPLQSAM-decoded' / 'BCPLQSAM.fb80').is_file())
        self.assertTrue((self.root / 'failure.json').is_file())
        self.assertTrue((self.root / 'panel-receipt.json').is_file())

    def test_repeat_fails_before_any_work(self):
        self.recover()
        self.decoder.process_calls=[]
        with self.assertRaisesRegex(mod.RecoverError, 'already complete'):
            self.recover()
        self.assertEqual(self.decoder.process_calls, [])

    def test_wrong_failed_job_refused(self):
        failure = json.loads((self.root / 'failure.json').read_text())
        failure['pilot_job'] = 1
        write_json(self.root / 'failure.json', failure)
        with self.assertRaisesRegex(mod.RecoverError, 'JES job number'):
            self.recover()
        self.assertEqual(self.decoder.process_calls, [])

    def test_wrong_stage_refused(self):
        f = self.root / 'failure.json'
        data = json.loads(f.read_text())
        data['stage'] = 'pilot'
        write_json(f, data)
        with self.assertRaisesRegex(mod.RecoverError, 'decode-stage'):
            self.recover()
        self.assertEqual(self.decoder.process_calls, [])

    def test_corrupted_previous_binary_refused(self):
        path = self.root / '01-BCPLDEMO-decoded' / 'BCPLDEMO.fb80'
        path.write_bytes(b'CORRUPT' * 12)
        with self.assertRaisesRegex(mod.RecoverError, 'saved decoded binary differs'):
            self.recover()
        self.assertEqual(self.decoder.process_calls, [])

    def test_prior_decoded_receipt_mismatch_refused(self):
        path = self.root / '02-BCPLTIME-decoded' / 'decode-receipt.json'
        info = json.loads(path.read_text())
        info['source_report_sha256'] = '0'*64
        write_json(path, info)
        with self.assertRaisesRegex(mod.RecoverError, 'prior decoder receipt'):
            self.recover()
        self.assertEqual(self.decoder.process_calls, [])

    def test_missing_prior_decode_refused(self):
        import shutil
        shutil.rmtree(self.root / '01-BCPLDEMO-decoded')
        with self.assertRaisesRegex(mod.RecoverError, 'outside failed ordinal'):
            self.recover()
        self.assertEqual(self.decoder.process_calls, [])

    def test_missing_pilot_refused(self):
        import shutil
        shutil.rmtree(self.pilots[2])
        with self.assertRaisesRegex(mod.RecoverError, 'missing original JES pilot'):
            self.recover()
        self.assertEqual(self.decoder.process_calls, [])

    def test_wrong_member_receipt_refused(self):
        path = self.pilots[1] / 'receipt.json'
        record = json.loads(path.read_text())
        record['requested_members'] = ['NOTMEMBR']
        write_json(path, record)
        with self.assertRaisesRegex(mod.RecoverError, 'JES job/dataset identity mismatch'):
            self.recover()
        self.assertEqual(self.decoder.process_calls, [])

    def test_wrong_dsn_refused(self):
        with self.assertRaisesRegex(mod.RecoverError, 'JES job/dataset identity mismatch'):
            mod.recover(self.panel, self.decoder, directory=self.root,
                        key=KEY, members=MEMBERS, source_dataset='HERC02.BCPL.WRONG')
        self.assertEqual(self.decoder.process_calls, [])

    def test_symlink_previous_binary_refused(self):
        path = self.root / '01-BCPLDEMO-decoded' / 'BCPLDEMO.fb80'
        path.unlink()
        path.symlink_to(self.root / '01-BCPLDEMO-decoded' / 'BCPLDEMO.fb80.json')
        with self.assertRaisesRegex(mod.RecoverError, 'linked evidence file'):
            self.recover()
        self.assertEqual(self.decoder.process_calls, [])

    def test_missing_failure_refused(self):
        (self.root / 'failure.json').unlink()
        with self.assertRaisesRegex(mod.RecoverError, 'evidence file'):
            self.recover()
        self.assertEqual(self.decoder.process_calls, [])

    def test_no_evidence_in_checkout(self):
        # Explicit rejection, without creating directories in any checkout.
        with self.assertRaisesRegex(mod.RecoverError, 'outside checkout'):
            mod.recover(self.panel, self.decoder, directory=ROOT,
                        key=KEY, members=MEMBERS, source_dataset=DSN)


if __name__ == '__main__':
    unittest.main()
